import { Settings } from "@/types";

import { Switch } from "../ui/Switch";
import SettingsCard from "./SettingsCard";
import SettingsRow from "./SettingsRow";
import { SETTINGS_CONTROL_END } from "./settingsControls";

interface ExportBrandingSettingsProps {
  settings: Settings;
  onUpdate: (newSettings: Settings) => void;
}

/**
 * Whether exported files advertise Nojoin. Install-wide and shown to
 * administrators only: the server ignores the key from anyone else.
 */
export default function ExportBrandingSettings({
  settings,
  onUpdate,
}: ExportBrandingSettingsProps) {
  return (
    <SettingsCard
      id="appearance-export-branding"
      title="Exported files"
      description="How PDF, Word and text exports look for everyone on this installation."
    >
      <SettingsRow
        label="Nojoin branding"
        description="On, exports open with the Nojoin letterhead and every page ends with a Generated by Nojoin line. Off, they carry a plain letterhead with no Nojoin logo, name or footer line, for documents you send to clients under your own name."
        controlClassName={SETTINGS_CONTROL_END}
      >
        <Switch
          checked={settings.export_branding !== false} // Default true
          onCheckedChange={(checked) =>
            onUpdate({ ...settings, export_branding: checked })
          }
        />
      </SettingsRow>
    </SettingsCard>
  );
}
