ALL_SECTIONS = ["transcript", "analytics", "notes"]


def _txt(parts=None, sections=ALL_SECTIONS, *, branded=True) -> str:
    document = build_document(parts or meeting_parts(), sections, branded=branded)
    return render(document, "txt").decode("utf-8")


def _pdf_text(parts=None, sections=ALL_SECTIONS, *, branded=True) -> str:
    payload = render(
        build_document(parts or meeting_parts(), sections, branded=branded), "pdf"
    )
    with pymupdf.open(stream=payload, filetype="pdf") as document:
        return "\n".join(page.get_text() for page in document)


def _pdf_link_targets(*, branded: bool) -> set[str]:
    """Every link annotation's URI across the PDF's pages."""
    payload = render(build_document(meeting_parts(), ["notes"], branded=branded), "pdf")
    with pymupdf.open(stream=payload, filetype="pdf") as document:
        return {
            link["uri"]
            for page in document
            for link in page.get_links()
            if "uri" in link
        }


