# -- embedded fonts --------------------------------------------------------------------------


def test_obfuscation_is_its_own_inverse_and_touches_only_the_header() -> None:
    font = bytes(range(256)) * 4
    key = uuid.UUID("01234567-89ab-cdef-0123-456789abcdef")

    hidden = obfuscate(font, key)

    assert hidden[32:] == font[32:]
    assert hidden[:32] != font[:32]
    assert obfuscate(hidden, key) == font


def test_docx_embeds_geist_regular_and_bold() -> None:
    payload = render(build_document(meeting_parts(), ["notes"]), "docx")
    with ZipFile(BytesIO(payload)) as archive:
        content_types = archive.read("[Content_Types].xml").decode()
        font_parts = [
            name for name in archive.namelist() if name.startswith("word/fonts/")
        ]
        font_table = archive.read("word/fontTable.xml").decode()
        settings = archive.read("word/settings.xml").decode()

    assert OBFUSCATED_FONT_CONTENT_TYPE in content_types
    assert len(font_parts) == 2
    assert 'w:name="Geist"' in font_table
    assert "w:embedRegular" in font_table and "w:embedBold" in font_table
    assert "w:embedTrueTypeFonts" in settings
