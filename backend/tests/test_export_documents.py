def test_delivery_comparisons_match_delivery_insights_ts() -> None:
    delivery = analytics_payload()["delivery"]
    readings = build_delivery_readings(
        delivery,
        {"k1": 600_000, "k2": 400_000},
        {
            "k1": {
                "meetings": 5,
                "words_per_minute": 150,
                "pitch_spread_semitones": 4.0,
                "pauses_per_minute": 2.0,
            }
        },
    )

    assert readings["k1"].pause_rate == 2.0
    assert readings["k1"].baseline == "faster than their usual across 5 meetings"
    assert readings["k2"].pitch_movement == "more varied than others here"
    assert readings["k1"].pitch_movement == "flatter than others here"
    assert readings["k2"].baseline is None


