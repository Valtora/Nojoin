def test_branded_exports_carry_the_letterhead_and_footer() -> None:
    assert "Generated by Nojoin" in _txt()
    pdf_text = _pdf_text()
    assert "Nojoin" in pdf_text
    assert "Generated by Nojoin" in pdf_text
    # The footer's site link is a real link annotation, not only text.
    assert _pdf_link_targets(branded=True) == {theme.SITE_URL}


def test_unbranded_exports_drop_the_letterhead_and_footer() -> None:
    # The analytics notes still name Nojoin where they explain how a figure
    # was measured; the setting removes the advertising, not the method.
    txt = _txt(branded=False)
    pdf_text = _pdf_text(branded=False)
    docx_bytes = render(
        build_document(meeting_parts(), ALL_SECTIONS, branded=False), "docx"
    )
    document = Document(BytesIO(docx_bytes))
    footers = " ".join(
        p.text
        for s in document.sections
        for f in (s.footer, s.first_page_footer)
        for p in f.paragraphs
    )

    assert "Nojoin \u00b7 Meeting record" not in txt
    assert "Generated by Nojoin" not in txt
    assert "Generated by Nojoin" not in pdf_text
    assert _pdf_link_targets(branded=False) == set()
    assert "Generated by Nojoin" not in footers
    assert document.core_properties.author == ""


