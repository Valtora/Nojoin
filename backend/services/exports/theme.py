def font_path(name: str) -> Path:
    return FONTS_DIR / FONT_FILES[name]


def accent(branded: bool) -> str:
    return BRAND if branded else NEUTRAL_ACCENT


@cache
def register_fonts() -> None:
    """Register Geist with ReportLab once per process.

    Also used by chart layout to measure text, so it lives here rather than in
    the PDF renderer.
    """
    from reportlab.lib.fonts import addMapping
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    for name in FONT_FILES:
        pdfmetrics.registerFont(TTFont(name, str(font_path(name))))
    # Lets Paragraph markup (<b>, <i>) resolve to the matching Geist face.
    addMapping(FONT_REGULAR, 0, 0, FONT_REGULAR)
    addMapping(FONT_REGULAR, 1, 0, FONT_BOLD)
    addMapping(FONT_REGULAR, 0, 1, FONT_ITALIC)
    addMapping(FONT_REGULAR, 1, 1, FONT_BOLD_ITALIC)


def text_width(text: str, font: str, size: float) -> float:
    from reportlab.pdfbase import pdfmetrics

    register_fonts()
    return float(pdfmetrics.stringWidth(text, font, size))


def _hex_to_rgb(value: str) -> tuple[int, int, int]:
    value = value.lstrip("#")
    return int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16)


def _rgb_to_hex(rgb: tuple[int, int, int]) -> str:
    return "#{:02x}{:02x}{:02x}".format(*rgb)


def _relative_luminance(rgb: tuple[int, int, int]) -> float:
    def channel(value: int) -> float:
        scaled = value / 255
        if scaled <= 0.03928:
            return scaled / 12.92
        return float(((scaled + 0.055) / 1.055) ** 2.4)

    red, green, blue = (channel(value) for value in rgb)
    return 0.2126 * red + 0.7152 * green + 0.0722 * blue


def contrast_on_white(value: str) -> float:
    return 1.05 / (_relative_luminance(_hex_to_rgb(value)) + 0.05)


@cache
def readable_on_white(value: str, minimum: float = 4.5) -> str:
    """The colour, darkened just enough to be read as text on white.

    Several speaker colours (yellow, lime, cyan) are bright enough for a dot or
    a bar and unreadable as a name. Darkening keeps the hue, so the name still
    reads as the same person as the bar beside it.
    """
    red, green, blue = _hex_to_rgb(value)
    # Each step takes 5% off every channel; 40 steps reaches near-black, which
    # passes any threshold, so the loop always ends on a readable colour.
    for _ in range(40):
        candidate = _rgb_to_hex((red, green, blue))
        if contrast_on_white(candidate) >= minimum:
            return candidate
        red, green, blue = int(red * 0.95), int(green * 0.95), int(blue * 0.95)
    return _rgb_to_hex((red, green, blue))
