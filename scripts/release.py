#!/usr/bin/env python3
"""Build, gate and publish a Nojoin release from the release host.

The images are built here rather than on GitHub's runners, and nothing reaches
the registry until every gate has passed:

1. Checks: origin/main is the release commit, docs/VERSION matches, the tag is
   new, and every commit since the previous tag has a green ``CI gate``.
2. Build: the four images from a clean worktree of that commit, with no layer
   cache, into OCI layouts under ~/.cache/nojoin-release.
3. Gates: Trivy on each layout with the release severity policy, the health and
   non-root smoke on the same images loaded into Docker, and an advisory lookup
   for the two subscription CLIs in worker-io, since Trivy cannot see into the
   Codex CLI's native binary.
4. Push: the same build again, from cache, with provenance and SBOM
   attestations. Each pushed image config must match the one that was scanned.
5. Tag: push vX.Y.Z. release.yml then checks the images came from the tag's
   commit, signs them, moves the rolling tags and writes the GitHub Release.

    python3 scripts/release.py 2.9.0             # release
    python3 scripts/release.py 2.9.0 --dry-run   # steps 1 to 3, nothing pushed
    python3 scripts/release.py 2.9.0 --dry-run --ref HEAD   # rehearse a branch

A dry run reports the publishing checks (version, tag, CI) instead of stopping
on them.

Needs docker with buildx, trivy, gh, and a ``docker login ghcr.io`` that can
write packages. See "Release Workflow" in docs/DEVELOPMENT.md.
"""

from __future__ import annotations

import argparse
import base64
import contextlib
import fcntl
import json
import os
import re
import secrets
import shutil
import subprocess
import sys
import time
from collections.abc import Callable, Iterator
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any
from urllib.parse import quote

REPO_ROOT = Path(__file__).resolve().parent.parent
GITHUB_REPO = "Valtora/Nojoin"
IMAGE_BASE = "ghcr.io/valtora/nojoin"
TARGETS = ("api", "worker", "worker-io", "frontend")
BUILDER = "nojoin-release"
# Disk-backed on purpose: /tmp is a small tmpfs on some hosts, and the worker
# layouts alone are over 8 GB.
WORK_ROOT = Path.home() / ".cache" / "nojoin-release"
SMOKE_PROJECT = "nojoin-release-smoke"
CI_CHECK = "CI gate"
CI_WAIT_SECONDS = 20 * 60
CI_START_GRACE_SECONDS = 2 * 60
VERSION_PATTERN = re.compile(r"^\d+\.\d+\.\d+$")

# Same severity policy the release gate has always applied; see SECURITY.md.
TRIVY_GATE = ["--severity", "CRITICAL,HIGH", "--ignore-unfixed", "--exit-code", "1"]

# The smoke runs docker-compose.example.yml under its own project name, so its
# containers, network and volumes cannot collide with a stack on this host.
SMOKE_OVERRIDE = """\
# Generated by scripts/release.py for the release smoke.
services:
  db:
    container_name: {project}-db
  redis:
    container_name: {project}-redis
  socket-proxy:
    container_name: {project}-socket-proxy
  api:
    container_name: {project}-api
    image: {api}
  frontend:
    container_name: {project}-frontend
    image: {frontend}
"""


class ReleaseError(Exception):
    """A check or gate failed. The message says which, and what to do next."""


@dataclass
class Release:
    version: str
    sha: str
    previous_tag: str | None
    dry_run: bool
    # Config digest of each image as built, scanned and smoke tested.
    configs: dict[str, str] = field(default_factory=dict)
    # Whether this run's builder may still exist, from create until remove_builder.
    builder: bool = False

    @property
    def tag(self) -> str:
        return f"v{self.version}"

    @property
    def work(self) -> Path:
        return WORK_ROOT / self.version

    @property
    def src(self) -> Path:
        return self.work / "src"

    @property
    def logs(self) -> Path:
        return self.work / "logs"

    def image(self, target: str) -> str:
        return f"{IMAGE_BASE}-{target}:{self.version}"

    def sha_image(self, target: str) -> str:
        return f"{IMAGE_BASE}-{target}:sha-{self.sha[:7]}"


def tail(path: Path, lines: int = 40) -> str:
    return "\n".join(path.read_text(errors="replace").splitlines()[-lines:])


def run(
    command: list[str],
    *,
    cwd: Path = REPO_ROOT,
    env: dict[str, str] | None = None,
    log: Path | None = None,
) -> str:
    """Run a command and return its stdout, or raise ReleaseError if it fails.

    With ``log`` the output goes to that file instead, and the error carries its
    last lines.
    """
    if log is None:
        result = subprocess.run(
            command, cwd=cwd, env=env, capture_output=True, text=True
        )
        if result.returncode != 0:
            detail = (result.stderr or result.stdout).strip()
            raise ReleaseError(f"{' '.join(command)} failed:\n{detail}")
        return result.stdout
    log.parent.mkdir(parents=True, exist_ok=True)
    with log.open("w") as handle:
        result = subprocess.run(
            command,
            cwd=cwd,
            env=env,
            stdout=handle,
            stderr=subprocess.STDOUT,
            text=True,
        )
    if result.returncode != 0:
        raise ReleaseError(f"{' '.join(command)} failed. End of {log}:\n{tail(log)}")
    return ""


@contextlib.contextmanager
def step(title: str, timings: list[tuple[str, float]]) -> Iterator[None]:
    print(f"\n== {title}", flush=True)
    start = time.monotonic()
    yield
    elapsed = time.monotonic() - start
    timings.append((title, elapsed))
    print(f"   done in {elapsed:.0f}s", flush=True)


def version_tuple(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in version.split("."))


# --- 1. Checks ---------------------------------------------------------------


def resolve_release(version: str, dry_run: bool, ref: str) -> Release:
    if not VERSION_PATTERN.match(version):
        raise ReleaseError(f"Version must be X.Y.Z, got {version!r}.")
    run(["git", "fetch", "--quiet", "--tags", "origin", "main"])
    sha = run(["git", "rev-parse", "--verify", f"{ref}^{{commit}}"]).strip()
    described = subprocess.run(
        [
            "git",
            "describe",
            "--tags",
            "--abbrev=0",
            "--match",
            "v[0-9]*.[0-9]*.[0-9]*",
            sha,
        ],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )
    previous = described.stdout.strip() if described.returncode == 0 else None

    problems = []
    file_version = run(["git", "show", f"{sha}:docs/VERSION"]).strip()
    if file_version != version:
        problems.append(
            f"docs/VERSION at {ref} is {file_version}, not {version}. "
            "Merge the version bump first."
        )
    if run(["git", "ls-remote", "--tags", "origin", f"refs/tags/v{version}"]).strip():
        problems.append(f"v{version} already exists on origin.")
    if previous and version_tuple(version) <= version_tuple(previous[1:]):
        problems.append(
            f"{version} is not newer than the previous release, {previous}."
        )
    if problems and not dry_run:
        raise ReleaseError("\n".join(problems))
    for problem in problems:
        print(f"   note: {problem} Ignored for a dry run.")
    return Release(version=version, sha=sha, previous_tag=previous, dry_run=dry_run)


def check_registry_login() -> None:
    config_dir = Path(os.environ.get("DOCKER_CONFIG", Path.home() / ".docker"))
    try:
        config = json.loads((config_dir / "config.json").read_text())
    except (OSError, ValueError):
        config = {}
    # Registry hosts are the keys of these two maps. An auths entry can be
    # empty when a credential store holds the secret, so test for the key.
    registries = {**config.get("auths", {}), **config.get("credHelpers", {})}
    if registries.get("ghcr.io") is not None:
        return
    raise ReleaseError(
        "Docker has no login for ghcr.io. Create a classic token with only the "
        "write:packages scope, then run:\n"
        "  docker login ghcr.io -u <github-user> --password-stdin"
    )


def ci_state(commit: str) -> tuple[str, str]:
    """Return (status, conclusion) of a commit's CI gate.

    GitHub creates the CI gate check only once the jobs it needs have finished,
    so while CI runs there is no check to read. The workflow run's status
    stands in for it until then.
    """
    path = (
        f"repos/{GITHUB_REPO}/commits/{commit}/check-runs?check_name={quote(CI_CHECK)}"
    )
    query = ".check_runs | sort_by(.started_at) | last | [.status, .conclusion] | @tsv"
    fields = run(["gh", "api", path, "--jq", query]).strip().split("\t")
    if len(fields) == 2 and fields[0] not in ("", "null"):
        return (fields[0], fields[1])
    runs = f"repos/{GITHUB_REPO}/actions/workflows/ci.yml/runs?head_sha={commit}&event=push"
    query = '.workflow_runs | sort_by(.created_at) | last | .status // ""'
    status = run(["gh", "api", runs, "--jq", query]).strip()
    if status and status != "completed":
        return (status, "")
    return ("missing", "")


def wait_for_ci(commits: list[str]) -> dict[str, tuple[str, str]]:
    """Poll until no commit's CI is still running, or CI_WAIT_SECONDS pass.

    A commit merged seconds ago may not have a workflow run yet, so a missing
    run counts as starting for the first CI_START_GRACE_SECONDS.
    """
    start = time.monotonic()
    states = {commit: ci_state(commit) for commit in commits}
    while time.monotonic() - start < CI_WAIT_SECONDS:
        starting = time.monotonic() - start < CI_START_GRACE_SECONDS
        waiting = [
            commit
            for commit, (status, _) in states.items()
            if status not in ("completed", "missing")
            or (status == "missing" and starting)
        ]
        if not waiting:
            break
        names = ", ".join(commit[:7] for commit in waiting)
        print(f"   CI still running on {names}, waiting", flush=True)
        time.sleep(20)
        states.update({commit: ci_state(commit) for commit in waiting})
    return states


def check_ci(release: Release) -> None:
    """Require a green CI gate on every commit since the previous release.

    CI on main only runs the jobs whose paths a push touched, so the release
    commit's own run is not enough: a version bump runs the docs checks and
    nothing else. Every commit in the range has to have passed.
    """
    span = (
        f"{release.previous_tag}..{release.sha}"
        if release.previous_tag
        else release.sha
    )
    commits = run(["git", "rev-list", "--first-parent", span]).split()
    if not release.previous_tag:
        commits = commits[:1]
    # Any commit in the range can still be under CI: a release usually follows
    # its version bump within minutes, and sometimes a late fix as well.
    failures = [
        f"{commit[:7]}: {conclusion or status}"
        for commit, (status, conclusion) in wait_for_ci(commits).items()
        if status != "completed" or conclusion != "success"
    ]
    if failures:
        raise ReleaseError(
            "CI gate is not green on every commit since "
            f"{release.previous_tag or 'the first commit'}:\n  " + "\n  ".join(failures)
        )
    print(f"   {len(commits)} commit(s) green")


# --- 2. Build ----------------------------------------------------------------


def prepare_worktree(release: Release) -> None:
    if release.src.exists():
        removed = subprocess.run(
            ["git", "worktree", "remove", "--force", str(release.src)],
            cwd=REPO_ROOT,
            capture_output=True,
        )
        if removed.returncode != 0:
            shutil.rmtree(release.src)
    run(["git", "worktree", "prune"])
    run(["git", "worktree", "add", "--detach", str(release.src), release.sha])


def ensure_builder(release: Release) -> None:
    """Create the release builder on the BuildKit image pinned in the release commit.

    The builder runs a privileged container, so it should not outlive the build:
    each run creates its own and remove_builder takes it down after the last bake.
    """
    pin = (release.src / "docker" / "Dockerfile.buildkit").read_text()
    match = re.search(r"^FROM\s+(\S+)", pin, re.MULTILINE)
    if not match:
        raise ReleaseError("docker/Dockerfile.buildkit has no FROM line.")
    image = match.group(1)
    leftover = subprocess.run(
        ["docker", "buildx", "inspect", BUILDER], capture_output=True
    )
    if leftover.returncode == 0:
        print(f"   removing the {BUILDER} builder an earlier run left behind")
        run(["docker", "buildx", "rm", BUILDER])
    # Marked before the create, which can leave a builder behind if bootstrap fails.
    release.builder = True
    run(
        [
            "docker", "buildx", "create", "--name", BUILDER, "--driver", "docker-container",
            "--driver-opt", f"image={image}", "--bootstrap",
        ]
    )  # fmt: skip


def remove_builder(release: Release) -> None:
    """Remove this run's builder, once.

    A failure only warns, so it cannot mask the release's own result or error.
    """
    if not release.builder:
        return
    release.builder = False
    removed = subprocess.run(
        ["docker", "buildx", "rm", BUILDER], capture_output=True, text=True
    )
    if removed.returncode != 0:
        detail = (removed.stderr or removed.stdout).strip()
        print(
            f"   warning: could not remove the {BUILDER} builder; remove it with "
            f"docker buildx rm {BUILDER}\n   {detail}",
            file=sys.stderr,
        )
        return
    print(f"   removed the {BUILDER} builder")


def bake(release: Release, name: str, *args: str) -> None:
    commit_time = int(run(["git", "log", "-1", "--format=%ct", release.sha]).strip())
    env = {
        **os.environ,
        "IMAGE_BASE": IMAGE_BASE,
        "VERSION": release.version,
        "REVISION": release.sha,
        "CREATED": datetime.fromtimestamp(commit_time, tz=UTC).strftime(
            "%Y-%m-%dT%H:%M:%SZ"
        ),
        # Fixes the image config's timestamps, so every bake of this commit
        # yields the same config digest and the push can be matched to the scan.
        "SOURCE_DATE_EPOCH": str(commit_time),
    }
    command = [
        "docker", "buildx", "bake", "--builder", BUILDER, "--file", "docker/release.hcl",
        f"--allow=fs.write={release.work}", "--progress", "plain", *args,
    ]  # fmt: skip
    run(command, cwd=release.src, env=env, log=release.logs / f"bake-{name}.log")


def image_config(index: dict[str, Any], fetch: Callable[[str], dict[str, Any]]) -> str:
    """Follow an OCI index down to the linux/amd64 image and return its config digest."""
    for descriptor in index["manifests"]:
        media_type = descriptor["mediaType"]
        if media_type.endswith("image.index.v1+json") or "manifest.list" in media_type:
            return image_config(fetch(descriptor["digest"]), fetch)
        platform = descriptor.get("platform", {})
        if platform.get("os") == "linux" and platform.get("architecture") == "amd64":
            return str(fetch(descriptor["digest"])["config"]["digest"])
    raise ReleaseError("The index holds no linux/amd64 image.")


def layout_config(layout: Path) -> str:
    def fetch(digest: str) -> dict[str, Any]:
        algorithm, value = digest.split(":", 1)
        return dict(json.loads((layout / "blobs" / algorithm / value).read_text()))

    return image_config(json.loads((layout / "index.json").read_text()), fetch)


def build_layouts(release: Release) -> None:
    outputs = []
    for target in TARGETS:
        layout = release.work / "oci" / target
        shutil.rmtree(layout, ignore_errors=True)
        outputs += ["--set", f"{target}.output=type=oci,dest={layout},tar=false"]
    bake(release, "build", "--no-cache", *outputs)
    for target in TARGETS:
        release.configs[target] = layout_config(release.work / "oci" / target)


# --- 3. Gates ----------------------------------------------------------------


def scan_images(release: Release) -> None:
    tmp = release.work / "tmp"
    tmp.mkdir(parents=True, exist_ok=True)
    env = {**os.environ, "TMPDIR": str(tmp)}
    # Update both databases once, so the parallel scans below only read them.
    run(["trivy", "image", "--download-db-only", "--quiet"], env=env)
    run(["trivy", "image", "--download-java-db-only", "--quiet"], env=env)
    release.logs.mkdir(parents=True, exist_ok=True)
    processes = {}
    for target in TARGETS:
        log = (release.logs / f"trivy-{target}.log").open("w")
        command = [
            "trivy", "image", "--input", str(release.work / "oci" / target),
            "--skip-db-update", "--skip-java-db-update", "--cache-backend", "memory",
            "--skip-version-check", "--table-mode", "detailed",
            *TRIVY_GATE,
            "--ignorefile", str(release.src / ".github" / "trivyignore"),
            "--secret-config", str(release.src / ".github" / "trivy-secret.yaml"),
        ]  # fmt: skip
        processes[target] = (
            subprocess.Popen(command, env=env, stdout=log, stderr=subprocess.STDOUT),
            log,
        )
    failed = []
    for target, (process, log) in processes.items():
        if process.wait() != 0:
            failed.append(target)
        log.close()
    if failed:
        reports = "\n\n".join(
            tail(release.logs / f"trivy-{target}.log") for target in failed
        )
        raise ReleaseError(f"Trivy gate failed for {', '.join(failed)}:\n{reports}")
    print("   Trivy: no fixable CRITICAL or HIGH findings")


def wait_healthy(container: str, timeout: int) -> None:
    deadline = time.monotonic() + timeout
    while True:
        status = (
            subprocess.run(
                [
                    "docker",
                    "inspect",
                    "--format",
                    "{{.State.Health.Status}}",
                    container,
                ],
                capture_output=True,
                text=True,
            ).stdout.strip()
            or "starting"
        )
        if status == "healthy":
            return
        if status == "unhealthy" or time.monotonic() > deadline:
            logs = subprocess.run(
                ["docker", "logs", "--tail", "60", container],
                capture_output=True,
                text=True,
            )
            raise ReleaseError(f"{container} is {status}:\n{logs.stdout}{logs.stderr}")
        time.sleep(5)


def assert_non_root(release: Release) -> None:
    """Check each image's long-running process drops to a non-root uid.

    api and worker images start as root only to repair the ./data ownership,
    then drop through gosu. ``docker exec id -u`` would report the image USER,
    so the api is read from PID 1 and the workers run ``id -u`` through their
    real entrypoint.
    """
    api_status = run(
        ["docker", "exec", f"{SMOKE_PROJECT}-api", "cat", "/proc/1/status"]
    )
    uids = {
        "api": next(
            (
                line.split()[1]
                for line in api_status.splitlines()
                if line.startswith("Uid:")
            ),
            "",
        ),
        "frontend": run(
            ["docker", "exec", f"{SMOKE_PROJECT}-frontend", "id", "-u"]
        ).strip(),
    }
    for target in ("worker", "worker-io"):
        uids[target] = run(
            ["docker", "run", "--rm", release.image(target), "id", "-u"]
        ).strip()
    root = [
        f"{name} runs as uid {uid or '?'}"
        for name, uid in uids.items()
        if uid in ("", "0")
    ]
    if root:
        raise ReleaseError("Non-root check failed:\n  " + "\n  ".join(root))
    print(
        "   non-root: " + ", ".join(f"{name} uid {uid}" for name, uid in uids.items())
    )


def smoke(release: Release) -> None:
    """Boot api and frontend with their real dependencies, as an operator would."""
    folder = release.work / "smoke"
    shutil.rmtree(folder, ignore_errors=True)
    folder.mkdir(parents=True)
    env_file = folder / ".env"
    key = base64.urlsafe_b64encode(os.urandom(32)).decode()
    env_file.write_text(
        f"FIRST_RUN_PASSWORD=smoke-{secrets.token_hex(8)}\nDATA_ENCRYPTION_KEY={key}\n"
    )
    override = folder / "override.yml"
    override.write_text(
        SMOKE_OVERRIDE.format(
            project=SMOKE_PROJECT,
            api=release.image("api"),
            frontend=release.image("frontend"),
        )
    )
    compose = [
        "docker", "compose", "--project-name", SMOKE_PROJECT,
        "--project-directory", str(folder), "--env-file", str(env_file),
        "--file", str(release.src / "docker-compose.example.yml"), "--file", str(override),
    ]  # fmt: skip
    try:
        run(
            [*compose, "up", "-d", "db", "redis", "socket-proxy", "api"],
            log=release.logs / "smoke-up.log",
        )
        wait_healthy(f"{SMOKE_PROJECT}-api", 300)
        run([*compose, "up", "-d", "frontend"], log=release.logs / "smoke-frontend.log")
        wait_healthy(f"{SMOKE_PROJECT}-frontend", 180)
        assert_non_root(release)
    finally:
        subprocess.run(
            [*compose, "down", "--volumes", "--remove-orphans"], capture_output=True
        )
    print("   smoke: api and frontend healthy")


def load_and_smoke(release: Release) -> None:
    outputs = [
        arg for target in TARGETS for arg in ("--set", f"{target}.output=type=docker")
    ]
    bake(release, "load", *outputs)
    if release.dry_run:
        # A dry run pushes nothing, so this was its last bake.
        remove_builder(release)
    for target in TARGETS:
        loaded = run(
            ["docker", "image", "inspect", release.image(target), "--format", "{{.Id}}"]
        )
        if loaded.strip() != release.configs[target]:
            raise ReleaseError(
                f"The {target} image loaded for the smoke is not the one scanned."
            )
    smoke(release)


def check_cli_advisories(release: Release) -> None:
    """Look up the worker-io subscription CLIs by their installed versions.

    Trivy cannot see into the Codex CLI's native binary, so its advisories come
    from here. The Claude Code CLI is looked up the same way for one record of
    both.
    """
    raw = run(
        [
            "docker", "run", "--rm", "--entrypoint", "cat", release.image("worker-io"),
            "/usr/local/share/nojoin/cli-versions.json",
        ]
    )  # fmt: skip
    hits = []
    versions = []
    for name, info in json.loads(raw)["dependencies"].items():
        versions.append(f"{name}@{info['version']}")
        found = run(
            [
                "gh", "api", f"advisories?ecosystem=npm&affects={name}@{info['version']}",
                "--jq", '.[] | .ghsa_id + " " + .severity + " " + .summary',
            ]
        )  # fmt: skip
        hits += [f"{name}@{info['version']}: {line}" for line in found.splitlines()]
    if hits:
        raise ReleaseError(
            "Advisories affect the worker-io CLIs. Rebuild once fixed releases are on npm:\n  "
            + "\n  ".join(hits)
        )
    print(f"   advisories: none for {', '.join(versions)}")


def run_gates(release: Release) -> None:
    with ThreadPoolExecutor(max_workers=2) as pool:
        futures = [
            pool.submit(scan_images, release),
            pool.submit(load_and_smoke, release),
        ]
        errors = [error for future in futures if (error := future.exception())]
    if errors:
        raise ReleaseError("\n\n".join(str(error) for error in errors))
    check_cli_advisories(release)


# --- 4. Push -----------------------------------------------------------------


def registry_json(reference: str, *extra: str) -> dict[str, Any]:
    return dict(
        json.loads(
            run(["docker", "buildx", "imagetools", "inspect", reference, *extra])
        )
    )


def verify_pushed(release: Release, target: str) -> None:
    repository = f"{IMAGE_BASE}-{target}"
    index = registry_json(release.image(target), "--raw")
    config = image_config(
        index, lambda digest: registry_json(f"{repository}@{digest}", "--raw")
    )
    if config != release.configs[target]:
        raise ReleaseError(
            f"{release.image(target)} has config {config}, but the scanned image "
            f"had {release.configs[target]}. Do not tag; rerun the release."
        )
    attested = any(
        descriptor.get("annotations", {}).get("vnd.docker.reference.type")
        == "attestation-manifest"
        for descriptor in index["manifests"]
    )
    if not attested:
        raise ReleaseError(
            f"{release.image(target)} was pushed without its attestations."
        )
    by_version = registry_json(release.image(target), "--format", "{{json .Manifest}}")
    by_sha = registry_json(release.sha_image(target), "--format", "{{json .Manifest}}")
    if by_version["digest"] != by_sha["digest"]:
        raise ReleaseError(
            f"{release.sha_image(target)} does not match {release.image(target)}."
        )


def push(release: Release) -> None:
    bake(release, "push", "--push", "--provenance=mode=max", "--sbom=true")
    # The last bake. Reading the pushed images back needs no builder.
    remove_builder(release)
    for target in TARGETS:
        verify_pushed(release, target)
    print("   pushed images match the scanned ones")


# --- 5. Tag ------------------------------------------------------------------


def find_release_run(release: Release) -> str:
    deadline = time.monotonic() + 120
    while time.monotonic() < deadline:
        listed = run(
            [
                "gh", "run", "list", "--repo", GITHUB_REPO, "--workflow", "release.yml",
                "--limit", "10", "--json", "databaseId,headBranch",
            ]
        )  # fmt: skip
        for entry in json.loads(listed):
            if entry["headBranch"] == release.tag:
                return str(entry["databaseId"])
        time.sleep(5)
    raise ReleaseError(
        f"No release.yml run appeared for {release.tag}. Check the Actions tab."
    )


def tag_and_publish(release: Release, wait: bool) -> None:
    existing = subprocess.run(
        ["git", "rev-parse", "-q", "--verify", f"refs/tags/{release.tag}^{{commit}}"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    ).stdout.strip()
    if existing and existing != release.sha:
        raise ReleaseError(
            f"A local {release.tag} points at {existing[:7]}. Delete it first."
        )
    if not existing:
        run(["git", "tag", release.tag, release.sha])
    run(["git", "push", "origin", f"refs/tags/{release.tag}"])
    if not wait:
        print(f"   pushed {release.tag}; release.yml signs and publishes it")
        return
    run_id = find_release_run(release)
    watched = subprocess.run(
        [
            "gh",
            "run",
            "watch",
            run_id,
            "--repo",
            GITHUB_REPO,
            "--exit-status",
            "--interval",
            "10",
        ]
    )
    if watched.returncode != 0:
        raise ReleaseError(
            f"release.yml run {run_id} failed. The rolling tags did not move."
        )
    url = run(
        ["gh", "release", "view", release.tag, "--repo", GITHUB_REPO, "--json", "url"]
    )
    print(f"   released: {json.loads(url)['url']}")


def clean_up(release: Release) -> None:
    images = [
        ref
        for target in TARGETS
        for ref in (release.image(target), release.sha_image(target))
    ]
    subprocess.run(["docker", "image", "rm", *images], capture_output=True)
    subprocess.run(
        ["git", "worktree", "remove", "--force", str(release.src)],
        cwd=REPO_ROOT,
        capture_output=True,
    )
    shutil.rmtree(release.work, ignore_errors=True)


def release_flow(args: argparse.Namespace, timings: list[tuple[str, float]]) -> Release:
    with step("Checks", timings):
        release = resolve_release(args.version, args.dry_run, args.ref)
        if not args.dry_run:
            check_registry_login()
        print(
            f"   {release.tag} from {release.sha[:7]}, previous {release.previous_tag}"
        )
        try:
            check_ci(release)
        except ReleaseError as error:
            if not args.dry_run:
                raise
            print(f"   note: {error}\n   Ignored for a dry run.")
    try:
        with step("Build from a clean worktree, no cache", timings):
            prepare_worktree(release)
            ensure_builder(release)
            build_layouts(release)
        with step("Gates: Trivy, smoke, CLI advisories", timings):
            run_gates(release)
        if args.dry_run:
            return release
        with step("Push with provenance and SBOM", timings):
            push(release)
    finally:
        # The last bake has already removed it, unless a step failed or was
        # interrupted before then.
        remove_builder(release)
    with step(f"Tag {release.tag} and publish", timings):
        tag_and_publish(release, wait=not args.no_wait)
    return release


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("version", help="the release version, X.Y.Z")
    parser.add_argument(
        "--dry-run", action="store_true", help="build and run every gate, push nothing"
    )
    parser.add_argument(
        "--no-wait",
        action="store_true",
        help="push the tag without watching release.yml",
    )
    parser.add_argument(
        "--ref",
        default="origin/main",
        help="commit to build; anything but origin/main needs --dry-run",
    )
    args = parser.parse_args()
    if args.ref != "origin/main" and not args.dry_run:
        parser.error("--ref is only for dry runs; a release is always origin/main")

    WORK_ROOT.mkdir(parents=True, exist_ok=True)
    timings: list[tuple[str, float]] = []
    with (WORK_ROOT / "release.lock").open("w") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            print("Another release run holds the lock.", file=sys.stderr)
            return 1
        try:
            release = release_flow(args, timings)
        except ReleaseError as error:
            print(f"\nRelease stopped: {error}", file=sys.stderr)
            print(f"Logs and build output are kept in {WORK_ROOT}.", file=sys.stderr)
            return 1
        clean_up(release)

    total = sum(seconds for _, seconds in timings)
    print(
        f"\n{'Dry run passed' if args.dry_run else 'Released'} in {total / 60:.1f} min"
    )
    for title, seconds in timings:
        print(f"  {seconds:5.0f}s  {title}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
